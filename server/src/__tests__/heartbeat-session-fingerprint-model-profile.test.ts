function sessionInput(overrides: Partial<SessionConfigInput> = {}): SessionConfigInput {
  return {
    adapterType: "codex_local",
    effectiveAdapterConfig: BASE_ADAPTER_CONFIG,
    agentRuntimeConfig: { heartbeat: { maxConcurrentRuns: 1 } },
    modelProfile: null,
    issueOverrides: null,
    workspaceConfig: { requestedMode: "agent_default", effectiveMode: "agent_default" },
    environment: { selectionSource: "default", selectedEnvironmentId: "environment-1" },
    environmentEnv: null,
    projectEnv: null,
    routineEnv: null,
    secretManifest: [
      {
        configPath: "env.OPENAI_API_KEY",
        envKey: "OPENAI_API_KEY",
        secretId: "secret-1",
        bindingId: "binding-1",
        version: 7,
        provider: "local_encrypted",
        outcome: "success",
      },
    ],
    runtimeSkills: [{ key: "paperclip", runtimeName: "paperclip", currentVersionId: "skill-version-1" }],
    agentConfigRevision: { id: "agent-config-revision-1", changedKeys: ["adapterConfig"] },
    ...overrides,
  };
}

function storedSessionParams(stored: { fingerprint: string; categoryFingerprints: Record<string, string> }) {
  return {
    sessionId: "thread-1",
    __paperclipConfiguredModel: "gpt-5.4-mini",
    __paperclipConfigFingerprint: stored.fingerprint,
    __paperclipConfigFingerprintVersion: 1,
    __paperclipConfigCategories: Object.keys(stored.categoryFingerprints),
    __paperclipConfigCategoryFingerprints: stored.categoryFingerprints,
  };
}

function freshness(stored: { fingerprint: string; categoryFingerprints: Record<string, string> }, next: SessionConfigMetadata, configuredModel = "gpt-5.4-mini") {
  return resolveTaskSessionConfigFreshness({
    hasTaskSession: true,
    configuredModel,
    taskSessionParams: { ...storedSessionParams(stored), __paperclipConfiguredModel: configuredModel },
    configMetadata: next,
  });
}

