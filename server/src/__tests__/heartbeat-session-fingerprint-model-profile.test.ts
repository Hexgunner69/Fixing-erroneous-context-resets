describe("session fingerprint model-profile normalization", () => {
  const tempDirs: string[] = [];
  afterAll(() => {
    for (const dir of tempDirs) rmSync(dir, { recursive: true, force: true });
  });

  it("keeps only the applied profile in the fingerprint category", () => {
    expect(normalizeModelProfileForSessionFingerprint(null)).toBeNull();
    expect(normalizeModelProfileForSessionFingerprint(DISABLED_CHEAP_REQUEST)).toBeNull();
    expect(normalizeModelProfileForSessionFingerprint(UNSUPPORTED_CHEAP_REQUEST)).toBeNull();
    expect(normalizeModelProfileForSessionFingerprint(APPLIED_CHEAP)).toEqual({
      applied: "cheap",
      configSource: "agent_runtime",
    });
  });

  it("does not fork the session for a disabled or unsupported profile request", async () => {
    const base = await buildEffectiveRunSessionConfigMetadata(sessionInput());
    for (const request of [DISABLED_CHEAP_REQUEST, UNSUPPORTED_CHEAP_REQUEST]) {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput({ modelProfile: request }));
      expect(next.fingerprint, request.fallbackReason).toBe(base.fingerprint);
      expect(next.categoryFingerprints).toEqual(base.categoryFingerprints);
      expect(freshness(base, next)).toMatchObject({ reset: false, changedCategories: [] });
    }
  });

  it("still resets when a profile is actually applied", async () => {
    const base = await buildEffectiveRunSessionConfigMetadata(sessionInput());
    const applied = await buildEffectiveRunSessionConfigMetadata(sessionInput({
      modelProfile: APPLIED_CHEAP,
      effectiveAdapterConfig: CHEAP_ADAPTER_CONFIG,
    }));
    const decision = freshness(base, applied, "gpt-5.4-nano");
    expect(decision.reset).toBe(true);
    expect(decision.changedCategories).toEqual(expect.arrayContaining(["modelProfile", "adapterConfig"]));
  });

  it("does not mask real configuration changes behind an ignored profile request", async () => {
    const instructionsRoot = mkdtempSync(path.join(tmpdir(), "paperclip-fingerprint-instructions-"));
    tempDirs.push(instructionsRoot);
    writeFileSync(path.join(instructionsRoot, "AGENTS.md"), "v1 instructions");
    const instructionsConfig = {
      ...BASE_ADAPTER_CONFIG,
      instructionsRootPath: instructionsRoot,
      instructionsEntryFile: "AGENTS.md",
    };
    const instructionsBase = await buildEffectiveRunSessionConfigMetadata(
      sessionInput({ effectiveAdapterConfig: instructionsConfig }),
    );
    writeFileSync(path.join(instructionsRoot, "AGENTS.md"), "v2 instructions");

    const base = await buildEffectiveRunSessionConfigMetadata(sessionInput());
    const cases: Array<{ name: string; category: string; stored: SessionConfigMetadata; input: Partial<SessionConfigInput> }> = [
      { name: "model", category: "adapterConfig", stored: base, input: { effectiveAdapterConfig: CHEAP_ADAPTER_CONFIG } },
      {
        name: "reasoning effort",
        category: "adapterConfig",
        stored: base,
        input: { effectiveAdapterConfig: { ...BASE_ADAPTER_CONFIG, modelReasoningEffort: "high" } },
      },
      {
        name: "issue effort override",
        category: "issueOverrides",
        stored: base,
        input: { issueOverrides: { adapterConfig: { modelReasoningEffort: "high" } } },
      },
      {
        name: "permissions",
        category: "adapterConfig",
        stored: base,
        input: { effectiveAdapterConfig: { ...BASE_ADAPTER_CONFIG, dangerouslyBypassApprovalsAndSandbox: true } },
      },
      { name: "instructions content", category: "instructions", stored: instructionsBase, input: { effectiveAdapterConfig: instructionsConfig } },
      {
        name: "tools / runtime skills",
        category: "runtimeSkills",
        stored: base,
        input: { runtimeSkills: [{ key: "paperclip", runtimeName: "paperclip", currentVersionId: "skill-version-2" }] },
      },
      {
        name: "environment",
        category: "environment",
        stored: base,
        input: { environment: { selectionSource: "default", selectedEnvironmentId: "environment-2" } },
      },
      { name: "environment env", category: "envBindings", stored: base, input: { projectEnv: { NEW_FLAG: "1" } } },
      {
        name: "secret version",
        category: "secrets",
        stored: base,
        input: {
          secretManifest: [
            {
              configPath: "env.OPENAI_API_KEY",
              envKey: "OPENAI_API_KEY",
              secretId: "secret-1",
              bindingId: "binding-1",
              version: 8,
              provider: "local_encrypted",
              outcome: "success",
            },
          ],
        },
      },
      {
        name: "workspace / trust isolation",
        category: "workspaceConfig",
        stored: base,
        input: { workspaceConfig: { requestedMode: "isolated_workspace", effectiveMode: "isolated_workspace" } },
      },
    ];

    for (const testCase of cases) {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput({
        ...testCase.input,
        modelProfile: DISABLED_CHEAP_REQUEST,
      }));
      const decision = freshness(testCase.stored, next);
      expect(decision.reset, testCase.name).toBe(true);
      expect(decision.changedCategories, testCase.name).toContain(testCase.category);
      expect(decision.changedCategories, testCase.name).not.toContain("modelProfile");
    }
  });

  describe("sessions checkpointed by 2026.824.1", () => {
    it("keeps the common no-request fingerprint byte-identical", async () => {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput());
      expect(next.fingerprint).toBe(LEGACY_824_1.noRequest.fingerprint);
      expect(next.categoryFingerprints).toEqual(LEGACY_824_1.noRequest.categoryFingerprints);
    });

    it("resumes a legacy session when a disabled request is now present (the reported reset)", async () => {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput({ modelProfile: DISABLED_CHEAP_REQUEST }));
      expect(freshness(LEGACY_824_1.noRequest, next)).toMatchObject({ reset: false, changedCategories: [] });
    });

    it("resumes a legacy session created under the same disabled request", async () => {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput({ modelProfile: DISABLED_CHEAP_REQUEST }));
      expect(next.fingerprint).not.toBe(LEGACY_824_1.disabledRequest.fingerprint);
      expect(freshness(LEGACY_824_1.disabledRequest, next)).toMatchObject({ reset: false, changedCategories: [] });
    });

    it("resumes a legacy session created under the same applied profile", async () => {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput({
        modelProfile: APPLIED_CHEAP,
        effectiveAdapterConfig: CHEAP_ADAPTER_CONFIG,
      }));
      expect(next.fingerprint).not.toBe(LEGACY_824_1.appliedProfile.fingerprint);
      expect(freshness(LEGACY_824_1.appliedProfile, next, "gpt-5.4-nano")).toMatchObject({
        reset: false,
        changedCategories: [],
      });
    });

    it("still resets a legacy applied-profile session when the profile is no longer applied", async () => {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput());
      const decision = freshness(LEGACY_824_1.appliedProfile, next);
      expect(decision.reset).toBe(true);
      expect(decision.changedCategories).toEqual(expect.arrayContaining(["modelProfile", "adapterConfig"]));
    });

    it("reports only the real change for a legacy disabled-request session", async () => {
      const next = await buildEffectiveRunSessionConfigMetadata(sessionInput({
        modelProfile: DISABLED_CHEAP_REQUEST,
        effectiveAdapterConfig: CHEAP_ADAPTER_CONFIG,
      }));
      const decision = freshness(LEGACY_824_1.disabledRequest, next);
      expect(decision.reset).toBe(true);
      expect(decision.changedCategories).toEqual(["adapterConfig"]);
    });
  });
});
